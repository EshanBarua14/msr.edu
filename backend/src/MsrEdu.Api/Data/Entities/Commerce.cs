/// <summary>A purchasable item: exactly one course or one plan.</summary>
public class Product
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public ProductKind Kind { get; set; }
    public Guid? CourseId { get; set; }
    public Guid? PlanId { get; set; }
    public required string Name { get; set; }
    public long PriceMinor { get; set; }
    public string Currency { get; set; } = "BDT";
    public long? PromoPriceMinor { get; set; }
    public DateTimeOffset? PromoStartsAt { get; set; }
    public DateTimeOffset? PromoEndsAt { get; set; }
    /// <summary>null = lifetime access (course products only).</summary>
    public int? AccessDays { get; set; }
    public SaleStatus Status { get; set; } = SaleStatus.Inactive;
    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;

    /// <summary>Authoritative current price. Checkout must use this, never a browser value.</summary>
    public long CurrentPriceMinor(DateTimeOffset at) =>
        PromoPriceMinor is { } promo
        && (PromoStartsAt is null || PromoStartsAt <= at)
        && (PromoEndsAt is null || PromoEndsAt > at)
            ? promo
            : PriceMinor;
}

